import { isScopedDoc } from "./scoped.js";
import type { Composition, Scope, SourceDoc, Variant } from "./types.js";
import { normalize } from "./util.js";

const DETAIL = "<!-- brief:detail -->";

export interface RenderInput {
  variant: Variant;
  composition: Composition;
  scope: Scope;
  personal: SourceDoc[];
  stacks: SourceDoc[];
  project: SourceDoc[];
}

/** Compose one markdown body from the selected layers. */
export function renderBrief(input: RenderInput): string {
  const docs = selectDocs(input);
  const parts: string[] = [header(input, docs)];
  for (const doc of docs) {
    const body = applyVariant(doc.body, input.variant);
    if (!body) continue;
    parts.push(withHeading(doc.title, body));
  }
  return normalize(parts.join("\n\n"));
}

export function selectDocs(input: RenderInput): SourceDoc[] {
  const project = input.project.filter((doc) => !isScopedDoc(doc));
  if (input.scope === "global") {
    return [...input.personal, ...input.stacks];
  }
  if (input.composition === "layered") {
    return [...input.stacks, ...project];
  }
  return [...input.personal, ...input.stacks, ...project];
}

export function applyVariant(body: string, variant: Variant): string {
  const text = body.replace(/\r\n/g, "\n");
  const index = text.indexOf(DETAIL);
  if (index === -1) return text.trim();
  if (variant === "short") return text.slice(0, index).trim();
  return `${text.slice(0, index)}${text.slice(index + DETAIL.length)}`.replace(/\n{3,}/g, "\n\n").trim();
}

function withHeading(title: string, body: string): string {
  const trimmed = body.trim();
  if (/^#\s+/m.test(trimmed.split("\n")[0] ?? "")) return trimmed;
  return `## ${title}\n\n${trimmed}`;
}

function header(input: RenderInput, docs: SourceDoc[]): string {
  const layers = describeLayers(docs);
  return [
    "# Builder brief",
    "",
    "Generated by brief. Do not edit this block by hand. Change the source layers (`~/.brief` and `.brief`) and run `brief compile`. To suggest a lasting change, run `brief propose` and accept it with `brief review`.",
    "",
    `Variant: ${input.variant}. Composition: ${input.composition}. Scope: ${input.scope}.`,
    layers ? `Layers: ${layers}.` : "Layers: (none yet).",
  ].join("\n");
}

function describeLayers(docs: SourceDoc[]): string {
  const personal = docs.filter((doc) => doc.layer === "personal").map((doc) => doc.relPath.replace(/\.md$/, ""));
  const stacks = docs.filter((doc) => doc.layer === "stack").map((doc) => doc.stackId ?? doc.relPath);
  const project = docs.filter((doc) => doc.layer === "project").map((doc) => doc.relPath.replace(/\.md$/, ""));
  const bits: string[] = [];
  if (personal.length) bits.push(`personal (${personal.join(", ")})`);
  if (stacks.length) bits.push(`stack (${stacks.join(", ")})`);
  if (project.length) bits.push(`project (${project.join(", ")})`);
  return bits.join(", ");
}
